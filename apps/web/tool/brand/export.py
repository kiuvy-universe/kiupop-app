"""Export KiuPop icons from the brand SVG using Python 3 and Pillow."""

from argparse import ArgumentParser
from io import BytesIO
from math import cos, hypot, radians, sin, tau
from pathlib import Path
from xml.etree import ElementTree as ET

from PIL import Image, ImageDraw, ImageFont

BRAND = Path(__file__).resolve().parent
APP = BRAND.parents[1]
RES = APP / "android/app/src/main/res"
WEB = APP / "web"
MASTER = ET.parse(BRAND / "kiupop-mark.svg").getroot()
NS = {"svg": "http://www.w3.org/2000/svg"}
_, _, VIEW, _ = map(float, MASTER.attrib["viewBox"].split())
CENTER = VIEW / 2
WHITE = MASTER.find("svg:rect", NS).attrib["fill"]
ORBIT = MASTER.find("svg:g", NS)
ELLIPSE = ORBIT.find("svg:ellipse", NS).attrib
DOT = MASTER.find("svg:circle", NS).attrib
VIOLET = DOT["fill"]
ANGLE, PIVOT_X, PIVOT_Y = map(
    float, ORBIT.attrib["transform"].removeprefix("rotate(").rstrip(")").split()
)
CX, CY, RX, RY, STROKE = (
    float(ELLIPSE[key]) for key in ("cx", "cy", "rx", "ry", "stroke-width")
)
DOT_X, DOT_Y, DOT_RADIUS = (float(DOT[key]) for key in ("cx", "cy", "r"))
assert ELLIPSE["stroke"] == VIOLET


def ellipse_outline(offset):
    """Sample the normal of the ellipse so its outline has a constant width."""
    c, s = cos(radians(ANGLE)), sin(radians(ANGLE))
    result = []
    for step in range(720):
        t = step * tau / 720
        u, v = cos(t), sin(t)
        nx, ny = u / RX, v / RY
        length = hypot(nx, ny)
        x = CX + RX * u + offset * nx / length - PIVOT_X
        y = CY + RY * v + offset * ny / length - PIVOT_Y
        result.append((PIVOT_X + c * x - s * y, PIVOT_Y + s * x + c * y))
    return result


OUTER = ellipse_outline(STROKE / 2)
INNER = ellipse_outline(-STROKE / 2)
MAX_RADIUS = max(
    max(hypot(x - CENTER, y - CENTER) for x, y in OUTER),
    hypot(DOT_X - CENTER, DOT_Y - CENTER) + DOT_RADIUS,
)


def mark(size, scale=1, *, rounded=False):
    supersample = 4
    full = size * supersample
    center = full / 2
    factor = full * scale / VIEW

    def project(x, y):
        return (center + (x - CENTER) * factor, center + (y - CENTER) * factor)

    canvas = Image.new("RGBA", (full, full), WHITE)
    pen = ImageDraw.Draw(canvas)
    pen.polygon([project(x, y) for x, y in OUTER], fill=VIOLET)
    pen.polygon([project(x, y) for x, y in INNER], fill=WHITE)
    pen.ellipse(
        [
            project(DOT_X - DOT_RADIUS, DOT_Y - DOT_RADIUS),
            project(DOT_X + DOT_RADIUS, DOT_Y + DOT_RADIUS),
        ],
        fill=VIOLET,
    )
    if rounded:
        mask = Image.new("L", canvas.size)
        ImageDraw.Draw(mask).rounded_rectangle(
            (0, 0, full - 1, full - 1), radius=full * 0.23, fill=255
        )
        canvas.putalpha(mask)
    else:
        canvas = canvas.convert("RGB")
    return canvas.resize((size, size), Image.Resampling.LANCZOS)


def png(image):
    buffer = BytesIO()
    image.save(buffer, "PNG", optimize=True)
    return buffer.getvalue()


def vector(dp, scale, color):
    edge = CX - RX
    opposite = CX + RX
    orbit = (
        f"M{edge:g},{CY:g} A{RX:g},{RY:g} 0 1,0 {opposite:g},{CY:g} "
        f"A{RX:g},{RY:g} 0 1,0 {edge:g},{CY:g} Z"
    )
    left = DOT_X - DOT_RADIUS
    right = DOT_X + DOT_RADIUS
    dot = (
        f"M{left:g},{DOT_Y:g} A{DOT_RADIUS:g},{DOT_RADIUS:g} 0 1,0 {right:g},{DOT_Y:g} "
        f"A{DOT_RADIUS:g},{DOT_RADIUS:g} 0 1,0 {left:g},{DOT_Y:g} Z"
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand/export.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{dp}dp" android:height="{dp}dp"
    android:viewportWidth="{VIEW:g}" android:viewportHeight="{VIEW:g}">
    <group android:pivotX="{CENTER:g}" android:pivotY="{CENTER:g}"
        android:scaleX="{scale:g}" android:scaleY="{scale:g}">
        <group android:pivotX="{PIVOT_X:g}" android:pivotY="{PIVOT_Y:g}"
            android:rotation="{ANGLE:g}">
            <path android:pathData="{orbit}" android:strokeColor="{color}"
                android:strokeWidth="{STROKE:g}"/>
        </group>
        <path android:pathData="{dot}" android:fillColor="{color}"/>
    </group>
</vector>
""".encode()


def social_image():
    """Cream canvas, porcelain card and pastel clay dots (KPOP-UX-002)."""
    image = Image.new("RGB", (1200, 630), "#FBF5EB")
    draw = ImageDraw.Draw(image)
    for (x, y, r, color) in (
        (1040, 120, 120, "#FFD8AE"),
        (1120, 300, 70, "#EFAED4"),
        (150, 560, 110, "#D7EBDC"),
        (60, 420, 60, "#D5E6F5"),
    ):
        draw.ellipse((x - r, y - r, x + r, y + r), fill=color)
    draw.rounded_rectangle((64, 64, 1136, 566), radius=56, fill="#FFFDF8", outline="#EADFD3")
    tile = mark(222, 0.9, rounded=True)
    draw.rounded_rectangle((150, 199, 384, 433), radius=56, fill="#F5ECDF")
    image.paste(tile, (156, 193), tile)
    font_file = APP / "assets/fonts/PlusJakartaSans.ttf"
    heading = ImageFont.truetype(font_file, 118)
    heading.set_variation_by_name("ExtraBold")
    draw.text((427, 288), "KiuPop", font=heading, fill="#302C33", anchor="lm")
    subtitle = ImageFont.truetype(font_file, 32)
    subtitle.set_variation_by_name("Medium")
    draw.text(
        (433, 378), "Tu tienda online en minutos.", font=subtitle, fill="#7E3BB9", anchor="lm"
    )
    return image


def exports():
    adaptive_scale = 0.58
    splash_scale = 0.60
    pwa_scale = 0.76
    assert MAX_RADIUS * adaptive_scale / VIEW * 108 < 33
    assert MAX_RADIUS * splash_scale / VIEW * 288 < 96
    assert MAX_RADIUS * pwa_scale / VIEW < 0.40

    yield APP / "assets/brand/kiupop-mark.png", png(mark(144, 0.94))
    yield WEB / "favicon.png", png(mark(32, 0.94))
    for size in (192, 512):
        yield WEB / f"icons/Icon-{size}.png", png(mark(size, 0.94))
        yield WEB / f"icons/Icon-maskable-{size}.png", png(mark(size, pwa_scale))
    yield WEB / "icons/kiupop-og.png", png(social_image())

    for density, size in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
        yield RES / f"mipmap-{density}/ic_launcher.png", png(mark(size, 0.90, rounded=True))
    yield RES / "drawable/ic_kiupop_foreground.xml", vector(108, adaptive_scale, VIOLET)
    yield RES / "drawable/ic_kiupop_monochrome.xml", vector(108, adaptive_scale, WHITE)
    yield RES / "drawable/ic_kiupop_notification.xml", vector(24, 0.90, WHITE)
    yield RES / "drawable/ic_kiupop_splash.xml", vector(288, splash_scale, "@color/kiupop_splash_mark")


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if exports differ from disk")
    args = parser.parse_args()
    stale = []
    count = 0
    for path, content in exports():
        count += 1
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                stale.append(str(path.relative_to(APP)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if stale:
        parser.exit(1, "Stale brand exports:\n" + "\n".join(stale) + "\n")
    print(f"{count} brand exports. Android glyph radius {MAX_RADIUS * 0.58 / VIEW * 108:.1f}/33 dp. "
          f"PWA glyph radius {MAX_RADIUS * 0.76 / VIEW:.1%}/40%.")


if __name__ == "__main__":
    main()
